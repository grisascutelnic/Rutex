// Function to get current language
function getCurrentLanguage() {
    const currentLang = document.querySelector('.current-lang')?.textContent;
    return currentLang === 'RO' ? 'ro' : 'ru';
}

// Function to translate city name
function translateCity(cityName, targetLanguage = null) {
    if (!cityName) return cityName;
    
    const targetLang = targetLanguage || getCurrentLanguage();
    const cityKey = cityName.toLowerCase().trim();
    
    // Check if we have a direct translation
    if (cityTranslations[cityKey] && cityTranslations[cityKey][targetLang]) {
        return cityTranslations[cityKey][targetLang];
    }
    
    // Check for partial matches (for cases like "Seliște, Chișinău")
    for (const [key, translations] of Object.entries(cityTranslations)) {
        if (cityKey.includes(key) && translations[targetLang]) {
            // Replace the matched part with translation
            const regex = new RegExp(key, 'gi');
            return cityName.replace(regex, translations[targetLang]);
        }
    }
    
    // If no translation found, return original
    return cityName;
}

// Function to translate all city names on the page
function translateAllCities() {
    const currentLang = getCurrentLanguage();
    
    // Translate ride locations
    const rideLocations = document.querySelectorAll('.ride-route .route-point span');
    rideLocations.forEach(span => {
        const originalText = span.getAttribute('data-original-text') || span.textContent;
        span.setAttribute('data-original-text', originalText);
        span.textContent = translateCity(originalText, currentLang);
    });
    
    // Translate filter inputs
    const filterInputs = document.querySelectorAll('#filter-from, #filter-to');
    filterInputs.forEach(input => {
        if (input.value) {
            const originalValue = input.getAttribute('data-original-value') || input.value;
            input.setAttribute('data-original-value', originalValue);
            input.value = translateCity(originalValue, currentLang);
        }
    });
    
    // Translate any other city references
    const cityElements = document.querySelectorAll('[data-city-name]');
    cityElements.forEach(element => {
        const cityName = element.getAttribute('data-city-name');
        element.textContent = translateCity(cityName, currentLang);
    });
}

// Function to reverse translate (for search functionality)
function reverseTranslateCity(cityName, sourceLanguage = null) {
    if (!cityName) return cityName;
    
    const sourceLang = sourceLanguage || getCurrentLanguage();
    const cityKey = cityName.toLowerCase().trim();
    
    // Find the Romanian version for search
    for (const [key, translations] of Object.entries(cityTranslations)) {
        if (translations[sourceLang] && translations[sourceLang].toLowerCase() === cityKey) {
            return translations['ro']; // Always return Romanian for search
        }
    }
    
    // If no reverse translation found, return original
    return cityName;
}

// Initialize city translations when page loads
document.addEventListener('DOMContentLoaded', function() {
    translateAllCities();
});

// Export functions for use in other scripts
window.CityTranslations = {
    translateCity,
    translateAllCities,
    reverseTranslateCity,
    getCurrentLanguage
};
